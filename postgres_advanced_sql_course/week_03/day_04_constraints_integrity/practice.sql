SELECT * FROM integrity_demo ORDER BY id;

-- Задание 3: create_fk_demo
-- Покажи отдельный TEMP TABLE demo с FOREIGN KEY.
DROP TABLE IF EXISTS integrity_child;
DROP TABLE IF EXISTS integrity_parent;
CREATE TEMP TABLE integrity_parent (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label TEXT NOT NULL UNIQUE
);

CREATE TEMP TABLE integrity_child (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id BIGINT NOT NULL REFERENCES integrity_parent(id),
    note TEXT NOT NULL
);

INSERT INTO integrity_parent (label)
VALUES ('task-group-a'), ('task-group-b');

INSERT INTO integrity_child (parent_id, note)
VALUES (1, 'linked row 1'),
       (2, 'linked row 2');

SELECT p.id AS parent_id,
       p.label,
       c.id AS child_id,
       c.note
FROM integrity_parent AS p
LEFT JOIN integrity_child AS c ON c.parent_id = p.id
ORDER BY p.id, c.id;

