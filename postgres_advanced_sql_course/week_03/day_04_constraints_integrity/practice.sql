-- Практика: constraints и integrity

-- Задание 1: list_constraints_for_tasks
-- Покажи ограничения на таблице tasks.
SELECT con.conname AS constraint_name,
       pg_get_constraintdef(con.oid) AS definition
FROM pg_constraint AS con
JOIN pg_class AS rel ON rel.oid = con.conrelid
WHERE rel.relname = 'tasks'
ORDER BY con.conname;

-- Задание 2: create_unique_check_demo
-- Создай TEMP TABLE с UNIQUE и CHECK.
DROP TABLE IF EXISTS integrity_demo;
CREATE TEMP TABLE integrity_demo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    severity TEXT NOT NULL CHECK (severity IN ('minor', 'major', 'critical'))
);

